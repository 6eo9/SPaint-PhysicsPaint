pub fn unit_categories() -> Vec<&'static str> {
    let mut out: Vec<&'static str> = UNITS.iter().map(|u| u.category).collect();
    out.sort_unstable();
    out.dedup();
    out
}

pub fn units_in(category: &str) -> impl Iterator<Item = &'static Unit> {
    UNITS.iter().filter(move |u| u.category == category)
}

/// Convert `value` from one unit to another using SI base units as the bridge.
pub fn convert(value: f64, from: &Unit, to: &Unit) -> Option<f64> {
    if from.category != to.category || to.factor == 0.0 {
        return None;
    }
    let base = (value + from.offset) * from.factor;
    Some(base / to.factor - to.offset)
}

/// Compact formatting that keeps very large and very small numbers readable.
pub fn format_number(value: f64) -> String {
    if value == 0.0 {
        return "0".to_owned();
    }
    let abs = value.abs();
    if abs >= 1e6 || abs < 1e-4 {
        format!("{value:.4e}")
    } else {
        let s = format!("{value:.6}");
        s.trim_end_matches('0').trim_end_matches('.').to_owned()
    }
}

/// The three positions of a formula triangle.
///
/// For `F = m a` the top is `F`, the lower left is `m` and the lower right is
/// `a`. For a quotient such as `v = s / t` the numerator `s` goes on top, so
/// covering a side reads the rearranged formula in the usual way.
///
/// `exact` is false for formulas that cannot be reduced to three real factors;
/// those fall back to `top = left × 1`, which still draws a valid triangle.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FormulaTriangle<'a> {
    pub top: &'a str,
    pub left: &'a str,
    pub right: &'a str,
    pub exact: bool,
}

fn relation_pos(s: &str) -> Option<(usize, usize)> {
    ["=", "≈", "≤", "≥", "∝", "→"]
        .iter()
        .filter_map(|rel| s.find(rel).map(|at| (at, rel.len())))
        .min_by_key(|(at, _)| *at)
}

fn top_level_pos(s: &str, needles: &[char]) -> Option<(usize, usize)> {
    let mut depth = 0_i32;
    for (i, ch) in s.char_indices() {
        match ch {
            '(' | '[' | '{' | '⟨' => depth += 1,
            ')' | ']' | '}' | '⟩' => depth -= 1,
            _ if depth == 0 && needles.contains(&ch) => return Some((i, ch.len_utf8())),
            _ => {}
        }
    }
    None
}

/// Byte ranges of whitespace-separated terms, ignoring whitespace inside
/// brackets (e.g. `2 r² (ρ_p − ρ_f) g` stays four terms, not seven).
fn token_ranges(s: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let mut start = 0;
    let mut depth = 0_i32;
    for (i, ch) in s.char_indices() {
        match ch {
            '(' | '[' | '{' | '⟨' => depth += 1,
            ')' | ']' | '}' | '⟩' => depth -= 1,
            _ if depth == 0 && ch.is_whitespace() => {
                if start < i {
                    out.push((start, i));
                }
                start = i + ch.len_utf8();
            }
            _ => {}
        }
    }
    if start < s.len() {
        out.push((start, s.len()));
    }
    out
}

fn strip_leading_sign(s: &str) -> &str {
    s.trim()
        .trim_start_matches(|c| matches!(c, '−' | '-' | '+' | '±'))
        .trim()
}

fn is_coefficient(s: &str) -> bool {
    let s = s.trim();
    s.parse::<f64>().is_ok()
        || (!s.is_empty()
            && s.chars().all(|c| {
                c.is_ascii_digit() || matches!(c, '½' | '¼' | '¾' | 'π' | 'τ' | '.' | '/')
            }))
}

/// Derive the triangle for any formula. Simple products and quotients get a
/// true three-quantity triangle; everything else is grouped into three terms
/// with a trailing `1`, so every row always has both representations.
pub fn triangle(formula: &Formula) -> FormulaTriangle<'_> {
    let expr = formula.expr;
    let Some((at, len)) = relation_pos(expr) else {
        return FormulaTriangle {
            top: expr.trim(),
            left: "1",
            right: "1",
            exact: false,
        };
    };
    let lhs = strip_leading_sign(&expr[..at]);
    let mut rhs = strip_leading_sign(&expr[at + len..]);
    if let Some((next, _)) = relation_pos(rhs) {
        rhs = strip_leading_sign(&rhs[..next]);
    }
    let exact_relation = &expr[at..at + len] == "=";

    if let Some((slash, slash_len)) = top_level_pos(rhs, &['/']) {
        let numerator = strip_leading_sign(&rhs[..slash]);
        let denominator = rhs[slash + slash_len..].trim();
        if !numerator.is_empty() && !denominator.is_empty() {
            return FormulaTriangle {
                top: numerator,
                left: lhs,
                right: denominator,
                exact: exact_relation,
            };
        }
    }

    if let Some((mul, mul_len)) = top_level_pos(rhs, &['*', '·', '×']) {
        let a = rhs[..mul].trim();
        let b = rhs[mul + mul_len..].trim();
        if !a.is_empty() && !b.is_empty() {
            return FormulaTriangle {
                top: lhs,
                left: a,
                right: b,
                exact: exact_relation,
            };
        }
    }

    // Sums and differences are not three-factor triangles. Keeping the whole
    // right-hand side with a trailing ×1 is honest and always drawable.
    if top_level_pos(rhs, &['+', '−', '-', '±']).is_some() {
        return FormulaTriangle {
            top: lhs,
            left: rhs,
            right: "1",
            exact: false,
        };
    }

    let tokens = token_ranges(rhs);
    if tokens.len() >= 2 {
        let (a, b) = (tokens[0], tokens[1]);
        let last = tokens[tokens.len() - 1].1;
        let (left, right) = if is_coefficient(&rhs[a.0..a.1]) && tokens.len() >= 3 {
            (&rhs[a.0..b.1], &rhs[tokens[2].0..last])
        } else {
            (&rhs[a.0..a.1], &rhs[b.0..last])
        };
        return FormulaTriangle {
            top: lhs,
            left,
            right,
            exact: exact_relation && tokens.len() == 2,
        };
    }

    FormulaTriangle {
        top: lhs,
        left: rhs,
        right: "1",
        exact: false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn unit(symbol: &str) -> &'static Unit {
        UNITS.iter().find(|u| u.symbol == symbol).unwrap()
    }

    #[test]
    fn length_conversion() {
        let result = convert(1.0, unit("km"), unit("m")).unwrap();
        assert!((result - 1000.0).abs() < 1e-9);
    }

    #[test]
    fn temperature_conversion() {
        let c_to_f = convert(100.0, unit("°C"), unit("°F")).unwrap();
        assert!((c_to_f - 212.0).abs() < 1e-9);
        let f_to_k = convert(32.0, unit("°F"), unit("K")).unwrap();
        assert!((f_to_k - 273.15).abs() < 1e-9);
    }

    #[test]
    fn incompatible_units_rejected() {
        assert!(convert(1.0, unit("m"), unit("kg")).is_none());
    }

    #[test]
    fn every_unit_has_unique_symbol_within_category() {
        for category in unit_categories() {
            let symbols: Vec<_> = units_in(category).map(|u| u.symbol).collect();
            for (i, a) in symbols.iter().enumerate() {
                assert!(!symbols[i + 1..].contains(a), "duplicate {a} in {category}");
            }
        }
    }

    fn formula(expr: &'static str) -> Formula {
        Formula {
            topic: "Test",
            name: "Test",
            expr,
            note: "",
        }
    }

    #[test]
    fn triangle_of_a_product_puts_the_subject_on_top() {
        let f = formula("F = m a");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("F", "m", "a"));
        assert!(t.exact);
    }

    #[test]
    fn triangle_of_a_quotient_puts_the_numerator_on_top() {
        let f = formula("v = Δx / Δt");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("Δx", "v", "Δt"));
        assert!(t.exact);

        let f = formula("F = G m₁ m₂ / r²");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("G m₁ m₂", "F", "r²"));
    }

    #[test]
    fn triangle_groups_coefficients_and_longer_products() {
        let f = formula("K = ½ m v²");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("K", "½ m", "v²"));

        let f = formula("p V = n R T");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("p V", "n", "R T"));

        let f = formula("T = 2π √(L / g)");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("T", "2π", "√(L / g)"));
    }

    #[test]
    fn every_formula_has_a_drawable_triangle() {
        for f in FORMULAS {
            let t = triangle(f);
            assert!(!t.top.is_empty(), "empty top for {}", f.expr);
            assert!(!t.left.is_empty(), "empty left for {}", f.expr);
            assert!(!t.right.is_empty(), "empty right for {}", f.expr);
        }
    }

    #[test]
    fn non_factorable_formulas_fall_back_to_times_one() {
        let f = formula("ΔU = Q − W");
        let t = triangle(&f);
        assert_eq!((t.top, t.left, t.right), ("ΔU", "Q − W", "1"));
        assert!(!t.exact);
    }
}
